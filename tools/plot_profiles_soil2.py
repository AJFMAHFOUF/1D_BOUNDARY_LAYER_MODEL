import numpy as np
import matplotlib.pyplot as plt
nlevs=14
expid='REF010'
dt=900 # frequency of storage defined in main.f90 (sec)
#nlev=80
nstep=int(48*3600/dt) + 1
nfreq=3600/dt
zs,ts,ws,ls,dw=np.loadtxt('../data_out/soil_profiles_exp_'+expid+'.dat',unpack=True)
zs1=np.reshape(zs,(nstep,nlevs))
ts1=np.reshape(ts,(nstep,nlevs))
ws1=np.reshape(ws,(nstep,nlevs))
ls1=np.reshape(ls,(nstep,nlevs))
dw1=np.reshape(dw,(nstep,nlevs))
fig=plt.figure()
ax1=fig.add_subplot(221)
ax1.set_title(expid)
ax1.plot(ts1[0,:]-273.15,zs1[0,:],label='09 LST',linewidth=2)
ax1.plot(ts1[int(3*nfreq),:]-273.15,zs1[1,:],label='12 LST',linewidth=2)
ax1.plot(ts1[int(6*nfreq),:]-273.15,zs1[2,:],label='15 LST',linewidth=2)
ax1.plot(ts1[int(9*nfreq),:]-273.15,zs1[2,:],label='18 LST',linewidth=2)
ax1.plot(ts1[int(12*nfreq),:]-273.15,zs1[0,:],label='21 LST',linewidth=2)
ax1.plot(ts1[int(15*nfreq),:]-273.15,zs1[1,:],label='00 LST',linewidth=2)
ax1.plot(ts1[int(18*nfreq),:]-273.15,zs1[2,:],label='03 LST',linewidth=2)
ax1.plot(ts1[int(21*nfreq),:]-273.15,zs1[2,:],label='06 LST',linewidth=2)
ax1.set_ylim(1.,0.)
ax1.legend(loc='best',fontsize='small')
ax1.set_xlabel('Soil temperature (°C)')
ax1.set_ylabel('Depth (m)')
ax2=fig.add_subplot(222)
ax2.set_title(expid)
ax2.plot(ws1[0,:],zs1[0,:],label='09 LST',linewidth=2)
ax2.plot(ws1[int(3*nfreq),:],zs1[1,:],label='12 LST',linewidth=2)
ax2.plot(ws1[int(6*nfreq),:],zs1[2,:],label='15 LST',linewidth=2)
ax2.plot(ws1[int(9*nfreq),:],zs1[2,:],label='18 LST',linewidth=2)
ax2.plot(ws1[int(12*nfreq),:],zs1[0,:],label='21 LST',linewidth=2)
ax2.plot(ws1[int(15*nfreq),:],zs1[1,:],label='00 LST',linewidth=2)
ax2.plot(ws1[int(18*nfreq),:],zs1[2,:],label='03 LST',linewidth=2)
ax2.plot(ws1[int(21*nfreq),:],zs1[2,:],label='06 LST',linewidth=2)
ax2.set_ylim(1.,0.)
ax2.legend(loc='best',fontsize='small')
ax2.set_xlabel('Soil moisture content (m3/m3)')
#ax2.set_ylabel('Height (m)')
ax3=fig.add_subplot(223)
ax3.plot(ls1[0,:],zs1[0,:],label='09 LST',linewidth=2)
ax3.plot(ls1[int(3*nfreq),:],zs1[1,:],label='12 LST',linewidth=2)
ax3.plot(ls1[int(6*nfreq),:],zs1[2,:],label='15 LST',linewidth=2)
ax3.plot(ls1[int(9*nfreq),:],zs1[2,:],label='18 LST',linewidth=2)
ax3.plot(ls1[int(12*nfreq),:],zs1[0,:],label='21 LST',linewidth=2)
ax3.plot(ls1[int(15*nfreq),:],zs1[1,:],label='00 LST',linewidth=2)
ax3.plot(ls1[int(18*nfreq),:],zs1[2,:],label='03 LST',linewidth=2)
ax3.plot(ls1[int(21*nfreq),:],zs1[2,:],label='06 LST',linewidth=2)
ax3.set_ylim(1.,0.)
ax3.legend(loc='best',fontsize='small')
ax3.set_xlabel('Thermal conductivity')
ax3.set_ylabel('Depth (m)')
ax4=fig.add_subplot(224)
ax4.plot(dw1[0,:]*1E6,zs1[0,:],label='09 LST',linewidth=2)
ax4.plot(dw1[int(3*nfreq),:]*1E6,zs1[1,:],label='12 LST',linewidth=2)
ax4.plot(dw1[int(6*nfreq),:]*1E6,zs1[2,:],label='15 LST',linewidth=2)
ax4.plot(dw1[int(9*nfreq),:]*1E6,zs1[2,:],label='18 LST',linewidth=2)
ax4.plot(dw1[int(12*nfreq),:]*1E6,zs1[0,:],label='21 LST',linewidth=2)
ax4.plot(dw1[int(15*nfreq),:]*1E6,zs1[1,:],label='00 LST',linewidth=2)
ax4.plot(dw1[int(18*nfreq),:]*1E6,zs1[2,:],label='03 LST',linewidth=2)
ax4.plot(dw1[int(21*nfreq),:]*1E6,zs1[2,:],label='06 LST',linewidth=2)
