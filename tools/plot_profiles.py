import numpy as np
import matplotlib.pyplot as plt
expid='REF028'
dt=900
nlev=80
nstep=int(48*3600/dt) + 1
nfreq=3600/dt
z,t,q,u,v,km,kh=np.loadtxt('../data_out/atmospheric_profiles_exp_'+expid+'.dat',unpack=True)
za=np.reshape(z,(nstep,80))
ta=np.reshape(t,(nstep,80))
qa=np.reshape(q,(nstep,80))
ua=np.reshape(u,(nstep,80))
va=np.reshape(v,(nstep,80))
kma=np.reshape(km,(nstep,80))
kha=np.reshape(kh,(nstep,80))
fig=plt.figure()
ax1=fig.add_subplot(221)
ax1.plot(ta[0,:]-273.15,za[0,:],label='09 LST',linewidth=2)
ax1.plot(ta[int(3*nfreq),:]-273.15,za[1,:],label='12 LST',linewidth=2)
ax1.plot(ta[int(6*nfreq),:]-273.15,za[2,:],label='15 LST',linewidth=2)
ax1.plot(ta[int(9*nfreq),:]-273.15,za[2,:],label='18 LST',linewidth=2)
ax1.set_ylim(0.,2000.)
ax1.legend(loc='best',fontsize='small')
ax1.set_xlabel('Potential temperature (°C)')
ax1.set_ylabel('Height (m)')
ax2=fig.add_subplot(222)
ax2.plot(qa[0,:]*1.E3,za[0,:],label='09 LST',linewidth=2)
